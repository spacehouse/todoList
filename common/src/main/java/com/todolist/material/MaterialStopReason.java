package com.todolist.material;

/**
 * 材料反推中「不再继续展开」的原因。
 *
 * <p>叶子材料节点会带上该原因，供预览界面展示"为什么到这里就停了"。
 */
public enum MaterialStopReason {
    /** 该物品没有任何可解析的配方，视为世界可直接获取的基础材料。 */
    NO_RECIPE,
    /** 命中终止条件（D7）：熔炼/烧制类配方的输入视为最终材料，不再继续反推。 */
    COOKING_INPUT,
    /** 递归路径上已出现过该物品（如 铁块 ↔ 铁锭），停止展开以避免死循环。 */
    CYCLE,
    /** 达到深度上限。 */
    MAX_DEPTH,
    /** 玩家在预览界面手动标记为「到此为止」。 */
    USER_STOPPED,
    /** 计划节点数达到上限，提前截断。 */
    NODE_LIMIT,
    /** 默认折叠：超过默认展开层数且玩家尚未要求「继续展开」。 */
    FOLDED
}
